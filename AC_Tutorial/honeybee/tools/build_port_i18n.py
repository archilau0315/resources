def join_parts(parts):
    out = ''
    for p in parts:
        if not p:
            continue
        if out:
            a, b = out[-1], p[0]
            latin = lambda ch: re.match(r'[A-Za-z0-9]', ch)
            cjk = lambda ch: '\u4e00' <= ch <= '\u9fff'
            if (latin(a) and latin(b)) or (latin(a) and cjk(b)) or (cjk(a) and latin(b)):
                out += ' '
        out += p
    return out


def translate(name):
    if name in EXACT:
        return EXACT[name]
    key = norm(name)
    if key in EXACT:
        return EXACT[key]
    if not key:
        return name
    return join_parts([TOKENS.get(w.lower()) or TOKENS.get(w) or w for w in split_tokens(key)])


def main():
    comps = json.load(open(COMP, encoding='utf-8'))
    names = []
    for c in comps:
        for p in c['in'] + c['out']:
            if p['n'] not in names:
                names.append(p['n'])
    table, missing, unknown = {}, [], {}
    for n in names:
        zh = translate(n)
        table[n] = zh
        if not zh:
            missing.append(n)
        for w in split_tokens(norm(n)):
            if w.lower() not in TOKENS and w not in TOKENS:
                unknown[w] = unknown.get(w, 0) + 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(table, f, ensure_ascii=False, indent=0, sort_keys=True)
    print('ports', len(table), 'missing', len(missing))
    top = sorted(unknown.items(), key=lambda kv: -kv[1])[:40]
    print('未收录 token：', ' '.join('%s(%d)' % (w, k) for w, k in top))
    print('avg KB', round(os.path.getsize(OUT) / 1024, 1))


if __name__ == '__main__':
    main()
